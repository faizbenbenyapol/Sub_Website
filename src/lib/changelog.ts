export const APP_VERSION = RELEASES[0].version;

/** ป้ายเวอร์ชันแสดงย้อนหลังได้มากสุดกี่เวอร์ชัน */
export const MAX_SHOWN_RELEASES = 5;

/** ประวัติที่ผู้ใช้เห็น: ตัดรายการหลังบ้านออก ข้ามเวอร์ชันที่มีแต่งานหลังบ้าน และเก็บแค่ 5 เวอร์ชันล่าสุด */
export function userReleases(releases: Release[] = RELEASES, limit = MAX_SHOWN_RELEASES): Release[] {
  return releases
    .map((r) => ({ ...r, changes: r.changes.filter((c) => !c.admin) }))
    .filter((r) => r.changes.length > 0)
    .slice(0, limit);
}
